  var NAMES = Object.keys(PLACES).sort(function (a, b) { return b.length - a.length; });
  var NAME_RE = new RegExp(
    "(^|[^0-9A-Za-zÀ-ÿ])(" +
    NAMES.map(function (n) { return n.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); }).join("|") +
    ")(?![A-Za-zÀ-ÿ])", "g");

  function parseRefs(str) {
    return str.split(",").map(function (r) {
      var m = /^(\d{1,2})([A-J]\d{1,2})?$/.exec(r);
      return m ? { page: m[1], grid: m[2] || "" } : null;
    }).filter(Boolean);
  }

  /* Choisit la carte dont l'époque colle le mieux à la date de l'événement.
     À égalité, la carte la plus resserrée dans le temps l'emporte ; les cartes
     générales (sans époque) ne servent qu'en dernier recours. */
  function bestMap(refs, year) {
    var best = null, bestScore = Infinity;
    refs.forEach(function (r) {
      var doc = PAGE2DOC[r.page];
      if (!doc) return;
      var era = CHAPTERS[doc] && CHAPTERS[doc].e;
      var score;
      if (!era) score = 1e6;
      else if (year >= era[0] && year <= era[1]) score = era[1] - era[0];
      else score = 1e5 + Math.min(Math.abs(year - era[0]), Math.abs(year - era[1]));
      if (score < bestScore) { bestScore = score; best = { ref: r, doc: doc }; }
    });
    return best;
  }

  function urls(doc) {
    var q = "wtlocale=F&prefer=lang&pub=gl&srcid=jwlshare&docid=" + doc;
    return { web: "https://www.jw.org/finder?" + q,
             app: "jwlibrary:///finder?" + q };
  }

  function linkOne(name, year) {
    var entry = PLACES[name];
    if (!entry) return null;
    var parts = entry.split("|");
    var pick = bestMap(parseRefs(parts[1]), year);
    if (!pick) return null;
    var u = urls(pick.doc);
    var info = CHAPTERS[pick.doc].t + " — carte p. " + pick.ref.page +
               (pick.ref.grid ? ", case " + pick.ref.grid : "");
    return '<a class="place" href="' + u.web + '" data-app="' + u.app +
           '" title="' + info.replace(/"/g, "&quot;") + '" target="_blank" rel="noopener">' +
           name + "</a>";
  }

  function inSegment(seg, year) {
    return seg.replace(NAME_RE, function (m, before, name) {
      var a = linkOne(name, year);
      return a ? before + a : m;
    });
  }

  /* Ne transforme que ce qui suit « Lieu : » ou « (lieu : … ) ». */
  function linkify(html, year) {
    html = String(html).replace(/(^|\n)(Lieu\s*:\s*)([^\n]*)/g,
      function (m, a, b, c) { return a + b + inSegment(c, year); });
    html = html.replace(/(\(\s*lieu\s*:\s*)([^)]*)/gi,
      function (m, a, b) { return a + inSegment(b, year); });
    return html;
  }

